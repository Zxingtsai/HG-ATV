"""Exercise local management UI with real official QR, then cancel. No login."""
import asyncio, datetime, json, os
from pathlib import Path
from playwright.async_api import async_playwright

NODE = '''
import {createService} from '/workspace/HG-ATV/server/src/main.mjs';
import {mkdtemp,rm} from 'node:fs/promises';import{tmpdir}from'node:os';import{join}from'node:path';
const dir=await mkdtemp(join(tmpdir(),'hg-ui-smoke-'));
const service=await createService({dataDir:dir},{media:{},playback:{close:async()=>{}},website:{},initializeMedia:false});
await new Promise(r=>service.server.listen(0,'127.0.0.1',r));
console.log(JSON.stringify({url:'http://127.0.0.1:'+service.server.address().port+'/account'}));
process.on('SIGTERM',async()=>{await service.close();await rm(dir,{recursive:true,force:true});process.exit(0)});
'''

async def main():
    env=dict(os.environ,HONGGUO_BROWSER_NO_SANDBOX='1')
    server=await asyncio.create_subprocess_exec('node','--input-type=module','-e',NODE,stdout=asyncio.subprocess.PIPE,stderr=asyncio.subprocess.DEVNULL,env=env)
    result={'at':datetime.datetime.now(datetime.timezone.utc).isoformat(),'scope':'Local admin UI only, QR generated by official anonymous flow; no scan, SMS, phone, QR payload or cookie retained.'}
    try:
        line=await asyncio.wait_for(server.stdout.readline(),10)
        url=json.loads(line)['url']
        async with async_playwright() as p:
            browser=await p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
            page=await browser.new_page(viewport={'width':1000,'height':1000})
            errors=[];page.on('pageerror',lambda e:errors.append(type(e).__name__))
            await page.goto(url)
            await page.locator('#status').filter(has_text='尚未登录').wait_for(timeout=15000)
            await page.get_by_role('button',name='生成登录二维码',exact=True).click()
            await page.locator('#qr').wait_for(state='visible',timeout=150000)
            result['qr_visible']=True
            result['qr_rendered']=await page.locator('#qr').evaluate('(x)=>x.complete&&x.naturalWidth>100')
            result['phone_confirmation_not_bypassed']=await page.locator('#status').inner_text()=='请用红果短剧 App 的“扫一扫”扫描二维码'
            await page.get_by_role('button',name='取消扫码',exact=True).click()
            await page.locator('#status').filter(has_text='尚未登录').wait_for(timeout=15000)
            result['qr_removed_on_cancel']=await page.locator('#qr').get_attribute('src') is None
            result['page_errors']=errors
            await browser.close()
    finally:
        server.terminate()
        try:await asyncio.wait_for(server.wait(),12)
        except asyncio.TimeoutError:server.kill();await server.wait()
    Path(__file__).with_name('smoke-ui-result.json').write_text(json.dumps(result,ensure_ascii=False,indent=2))
    print(json.dumps(result,ensure_ascii=False))
    assert result.get('qr_rendered') and result.get('qr_removed_on_cancel') and not result.get('page_errors')

asyncio.run(main())
